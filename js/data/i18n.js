export function detectBrowserLanguage() {
  const navLangs = navigator.languages || [navigator.language || navigator.userLanguage || 'en'];
  for (const nl of navLangs) {
    if (!nl) continue;
    const code = nl.split('-')[0].toLowerCase();
    if (supportedLanguages[code]) {
      return code;
    }
  }
  return 'en';
}

export function getLanguage() {
  const saved = localStorage.getItem('calc_hub_lang') || localStorage.getItem('calc_language');
  if (saved && supportedLanguages[saved]) {
    return saved;
  }
  return detectBrowserLanguage();
}

export function setLanguage(lang) {
  if (supportedLanguages[lang]) {
    localStorage.setItem('calc_hub_lang', lang);
    localStorage.setItem('calc_language', lang);
    const dir = supportedLanguages[lang].dir || 'ltr';
    document.documentElement.setAttribute('dir', dir);
    document.documentElement.setAttribute('lang', lang);
    window.dispatchEvent(new CustomEvent('language-changed', { detail: { lang, dir } }));
  }
}

export function t(key) {
  const lang = getLanguage();
  const dict = translations[lang] || translations.en;
  return dict[key] || translations.en[key] || key;
}
